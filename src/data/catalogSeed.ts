export const PRODUCT_VARIANTS: ProductVariantEntity[] = PRODUCT_SEED_SPECS.flatMap((spec) => {
  const sizes =
    spec.sizeGroup === 'one_size'
      ? ACCESSORY_ONE_SIZE
      : spec.sizeGroup === 'belt'
        ? BELT_SIZES
        : spec.sizeGroup === 'footwear' || spec.legacyCategory === 'FOOTWEAR'
          ? FOOTWEAR_SIZES
          : APPAREL_SIZES;

  const colors = spec.altColor
    ? [
        { slug: spec.colorSlug, name: spec.colorName, hex: spec.swatchColor },
        spec.altColor,
      ]
    : [{ slug: spec.colorSlug, name: spec.colorName, hex: spec.swatchColor }];

  const variants: ProductVariantEntity[] = [];
  colors.forEach((col, cIdx) => {
    sizes.forEach((size, sIdx) => {
      const qty = spec.stockStatus === 'low_stock' ? ((sIdx + cIdx) % 3) + 1 : 12 - sIdx;
      variants.push({
        id: `${spec.id}-${col.slug}-${size.toLowerCase()}`,
        productId: spec.id,
        sku: `${spec.sku}-${col.slug.slice(0, 3).toUpperCase()}-${size}`,
        size,
        colorSlug: col.slug,
        colorName: col.name,
        colorHex: col.hex,
        stockQty: qty,
        stockStatus: qty <= 2 ? 'low_stock' : 'in_stock',
      });
    });
  });
  return variants;
});

