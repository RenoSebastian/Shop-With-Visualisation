// Build Look <-> FilterOption junction including editorial look tags + inherited garment/material tags from associated products
export const LOOK_FILTER_OPTIONS: LookFilterOptionJunction[] = (() => {
  const result: LookFilterOptionJunction[] = [];
  const seen = new Set<string>();

  const pushUnique = (lookId: string, optionId: string, source: 'editorial' | 'inherited_from_product') => {
    const key = `${lookId}::${optionId}`;
    if (seen.has(key)) return;
    seen.add(key);
    result.push({ lookId, optionId, source });
  };

  Object.entries(LOOK_EDITORIAL_TAXONOMY).forEach(([lookId, optionIds]) => {
    optionIds.forEach((optionId) => pushUnique(lookId, optionId, 'editorial'));
  });

  // Inherit garment category & material metadata from associated products automatically
  const productOptsByProductId = new Map<string, string[]>();
  PRODUCT_FILTER_OPTIONS.forEach((pfo) => {
    const list = productOptsByProductId.get(pfo.productId) ?? [];
    list.push(pfo.optionId);
    productOptsByProductId.set(pfo.productId, list);
  });

  LOOK_PRODUCT_JUNCTIONS.forEach((lp) => {
    const opts = productOptsByProductId.get(lp.productId) ?? [];
    opts.forEach((optId) => {
      if (optId.startsWith('garment-') || optId.startsWith('material-')) {
        pushUnique(lp.lookId, optId, 'inherited_from_product');
      }
    });
  });

  return result;
})();

